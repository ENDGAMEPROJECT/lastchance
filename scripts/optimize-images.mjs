/* Makes a lighter .webp copy of every raster image in public/ (originals are
   kept), resized to what the 1280x720 stage can show, and writes the
   original -> webp map that game/assets.js reads. Re-run after adding or
   replacing an image. sharp is not a project dependency, so install it
   first without saving it:  npm install sharp --no-save
   then:  node scripts/optimize-images.mjs */
import fs from 'node:fs'
import path from 'node:path'
import sharp from 'sharp'

const PUBLIC = 'public'
const SKIP = ['bg/obsolete_for_now/']
const BIG = ['bg/', 'algorithm-room/', 'ending/'] // full-screen art: fit 1920x1080
const exts = /\.(png|jpe?g|gif)$/i

const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
  const p = path.join(dir, d.name)
  return d.isDirectory() ? walk(p) : [p]
})

const files = walk(PUBLIC).map((p) => path.relative(PUBLIC, p).split(path.sep).join('/'))
  .filter((r) => exts.test(r) && !SKIP.some((s) => r.startsWith(s)))
const stems = new Map()
for (const r of files) { const s = r.replace(exts, ''); stems.set(s, (stems.get(s) || 0) + 1) }

const map = {}
const rows = []
let before = 0, after = 0
for (const rel of files) {
  const src = path.join(PUBLIC, rel)
  const isGif = /\.gif$/i.test(rel)
  const stem = rel.replace(exts, '')
  const outRel = (stems.get(stem) > 1 && isGif ? `${stem}-anim` : stem) + '.webp'
  const out = path.join(PUBLIC, outRel)
  const box = BIG.some((b) => rel.startsWith(b)) ? [1920, 1080] : [1280, 1280]
  const img = sharp(src, isGif ? { animated: true } : {})
  const meta = await img.metadata()
  const pipeline = img.resize({ width: box[0], height: box[1], fit: 'inside', withoutEnlargement: true })
    .webp(isGif ? { quality: 60, effort: 6, mixed: true, minSize: true } : { quality: 82, effort: 5, alphaQuality: 90 })
  await pipeline.toFile(out)
  const a = fs.statSync(src).size, b = fs.statSync(out).size
  if (b > a * 0.9) { fs.unlinkSync(out); rows.push([rel, a, a, 'kept original']); before += a; after += a; continue }
  map[rel] = outRel
  before += a; after += b
  rows.push([rel, a, b, `${meta.width}x${meta.pageHeight || meta.height}${isGif ? ` ${meta.pages}f` : ''}`])
}

const lines = Object.entries(map).sort().map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
fs.writeFileSync('src/game/webpAssets.js',
  `/* GENERATED by scripts/optimize-images.mjs — do not edit by hand.\r\n` +
  `   Original image path (relative to public/) -> its optimised .webp copy.\r\n` +
  `   bgUrl()/assetUrl() in assets.js serve the webp whenever one is listed. */\r\n` +
  `export const WEBP = {\r\n${lines.join('\r\n')}\r\n}\r\n`)

rows.sort((x, y) => y[1] - x[1])
fs.mkdirSync('junk', { recursive: true }); fs.writeFileSync('junk/webp_report.tsv', rows.map((r) => [r[0], (r[1] / 1048576).toFixed(2), (r[2] / 1048576).toFixed(2), r[3]].join('\t')).join('\n'))
console.log(`converted ${Object.keys(map).length}/${files.length}; ${(before / 1048576).toFixed(1)} MB -> ${(after / 1048576).toFixed(1)} MB`)
for (const r of rows.slice(0, 12)) console.log(`${(r[1] / 1048576).toFixed(1).padStart(5)} -> ${(r[2] / 1048576).toFixed(2).padStart(5)} MB  ${r[0]}  ${r[3]}`)
